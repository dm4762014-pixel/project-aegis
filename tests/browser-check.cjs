const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('fs');
const path=require('path');
const output=process.env.SCREENSHOT_DIR || path.join(process.cwd(),'results');
fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1200,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8000/ai-lab');
 await page.locator('#model option').first().waitFor({state:'attached'});
 await page.locator('#comparison tr').nth(3).waitFor();
 if(!(await page.locator('#experiment-status').innerText()).startsWith('Verified run'))throw Error('Comparison not verified');
 await page.locator('#model').selectOption('qwen2.5:0.5b');
 await page.locator('#prompt').fill('Reply with exactly: Local AI works.');
 await page.locator('#send').click();
 await page.waitForFunction(()=>!document.getElementById('send').disabled,{},{timeout:190000});
 const answer=await page.locator('#answer').innerText();
 if(!answer.trim())throw Error('Real UI inference failed: '+await page.locator('#status').innerText());
 await page.locator('#send').click();
 await page.waitForFunction(()=>!document.getElementById('send').disabled,{},{timeout:190000});
 const status=await page.locator('#status').innerText();
 if(!status.includes('CACHE_HIT'))throw Error('Repeat was not cached');
 await page.screenshot({path:path.join(output,'local-ai-mesh-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.screenshot({path:path.join(output,'local-ai-mesh-mobile.png'),fullPage:true});
 if(overflow||errors.length)throw Error(JSON.stringify({overflow,errors}));
 const report={mode:'headless Chromium with real Ollama; no request mocks',answer,status,mobile_horizontal_overflow:overflow,page_errors:errors,passed:true};
 fs.writeFileSync('results/browser-check.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
